// Which requests the Service Worker handles (task #192, ADR-0028). Holds only pure functions using neither DOM nor Service Worker types
// (imported by the Service Worker bundle and tests. ⚠ Not by the UI bundle —— that would make the chunk shared, and the Service Worker
// would import another chunk and break. The build in vite.config.ts checks for this and fails).
//
// It handles **only the app shell (static files)**. These pass through (responses not replaced, not cached):
// - `/api/*` —— data and sign-in round trips (`/api/auth/*` redirects to assay; ⚠ intercepting the redirect breaks it) and the version (`/api/info`)
// - `/app/*` —— the time-tracking app (wbstimer) sign-in return URL `/app/oauth2redirect` (ADR-0019).
//   It is a URL received by Android App Links, so when opened in a browser the server's answer is shown as is
// - `/.well-known/*` —— App Links verification file (assetlinks.json; content generated by the api)
// - `/sw.js` —— the Service Worker itself (the browser fetches it bypassing the Service Worker for update checks, but just in case)
// - non-GET and other origins (Google Fonts etc.)

export type RequestRoute =
  /** Not handled (the browser goes straight to the network) */
  | 'network'
  /** A navigation. Returns the shell (index.html) */
  | 'shell-page'
  /** A static file. Returned from the shell if present, otherwise from the network */
  | 'shell-file';

export interface RequestFacts {
  method: string;
  url: string;
  /** Request.mode ('navigate' is a navigation) */
  mode: string;
}

/** Path prefixes to pass through. Each matches "that path itself" or "below it" */
export const NETWORK_ONLY_PREFIXES = ['/api', '/app', '/.well-known'] as const;

const SERVICE_WORKER_PATH = '/sw.js';

const isUnder = (pathname: string, prefix: string): boolean =>
  pathname === prefix || pathname.startsWith(`${prefix}/`);

/** How to handle a request. *origin* is the Service Worker's origin (self.location.origin). */
export const routeOf = (request: RequestFacts, origin: string): RequestRoute => {
  if (request.method !== 'GET') return 'network';
  const url = new URL(request.url);
  if (url.origin !== origin) return 'network';
  if (url.pathname === SERVICE_WORKER_PATH) return 'network';
  if (NETWORK_ONLY_PREFIXES.some((prefix) => isUnder(url.pathname, prefix))) return 'network';
  return request.mode === 'navigate' ? 'shell-page' : 'shell-file';
};

/** Shell cache name. Separate per version; old names are deleted when a new version activates */
export const SHELL_CACHE_PREFIX = 'wbs-shell-';

export const shellCacheName = (version: string): string => `${SHELL_CACHE_PREFIX}${version}`;

/** Caches that may be deleted when a version activates (only old versions created by this Service Worker) */
export const staleShellCaches = (cacheNames: readonly string[], version: string): string[] =>
  cacheNames.filter((name) => name.startsWith(SHELL_CACHE_PREFIX) && name !== shellCacheName(version));

/** Whether a response may go into the shell. Redirects, errors or foreign responses in the shell would be shown when opened offline */
export const isShellWorthy = (response: { ok: boolean; redirected: boolean; type: string }): boolean =>
  response.ok && !response.redirected && response.type === 'basic';

/**
 * Message that activates the new version (sent from the UI to the waiting Service Worker).
 * ⚠ The UI side (`src/pwa/appUpdate.ts`) holds the same value. Importing this file from the UI bundle
 * would share a chunk between Service Worker and UI, making the Service Worker import another chunk and break (a test checks they match)
 */
export const SKIP_WAITING_MESSAGE = 'SKIP_WAITING';
